// captureSink collects the log records emitted through a logr.Logger so the
// tests can assert that keystore passwords never reach the log output.
type captureSink struct {
	messages []string
}

func (s *captureSink) Init(logr.RuntimeInfo) {}
func (s *captureSink) Enabled(int) bool      { return true }
func (s *captureSink) Info(_ int, msg string, kv ...interface{}) {
	s.messages = append(s.messages, logRecord(msg, kv...))
}
func (s *captureSink) Error(_ error, msg string, kv ...interface{}) {
	s.messages = append(s.messages, logRecord(msg, kv...))
}
func (s *captureSink) WithValues(...interface{}) logr.LogSink { return s }
func (s *captureSink) WithName(string) logr.LogSink           { return s }

func logRecord(msg string, kv ...interface{}) string {
	if len(kv) == 0 {
		return msg
	}
	return fmt.Sprint(append([]interface{}{msg}, kv...)...)
}

// TestProvidedPasswordSealsTheKeystore verifies that the password handed to
// the keystore builders is the one the produced JKS is sealed with: decoding
// with it succeeds, and decoding with any other password fails the JKS
// integrity check.
func TestProvidedPasswordSealsTheKeystore(t *testing.T) {
	ca, err := testutil.GenerateTestCA()
	if err != nil {
		t.Fatalf("failed to generate CA: %v", err)
	}
	uc, err := testutil.GenerateTestUserCert(ca, "test1234")
	if err != nil {
		t.Fatalf("failed to generate user cert: %v", err)
	}

	cp := NewCertProcessor(logr.Logger{})
	ctx := context.Background()

	tests := map[string]struct {
		build func() ([]byte, error)
	}{
		"CreateTruststore": {
			build: func() ([]byte, error) {
				b, _, err := cp.CreateTruststore(ctx, ca.CACertPEM, "test1234")
				return b, err
			},
		},
		"CreateKeystore": {
			build: func() ([]byte, error) {
				b, _, err := cp.CreateKeystore(ctx, ca.CACertPEM, uc.UserCertPEM, uc.UserKeyPEM, "", "test1234")
				return b, err
			},
		},
		"GenerateTLSforHTTP": {
			build: func() ([]byte, error) {
				b, _, err := cp.GenerateTLSforHTTP(ctx, ca.CACertPEM, ca.CAKeyPEM, "test1234", "confluent-schema-registry", "kafka")
				return b, err
			},
		},
		"ConvertPEMToJKS": {
			build: func() ([]byte, error) {
				b, _, err := cp.ConvertPEMToJKS(ctx, uc.UserCertPEM, uc.UserKeyPEM, "", "test1234")
				return b, err
			},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			jks, err := tt.build()
			if err != nil {
				t.Fatalf("failed to build the keystore: %v", err)
			}

			store := keystore.New()
			if err := store.Load(bytes.NewReader(jks), []byte("test1234")); err != nil {
				t.Errorf("expected the provided password to open the keystore, got %v", err)
			}

			wrong := keystore.New()
			if err := wrong.Load(bytes.NewReader(jks), []byte("test1234-wrong")); err == nil {
				t.Error("expected a wrong password to fail the JKS integrity check")
			}
		})
	}
}

// TestEmptyPasswordIsAutoGenerated verifies that an empty password makes the
// keystore builders generate one with GeneratePassword(24, true, false) and
// return it: 24 characters, letters and digits only, and the produced JKS
// opens with it.
func TestEmptyPasswordIsAutoGenerated(t *testing.T) {
	ca, err := testutil.GenerateTestCA()
	if err != nil {
		t.Fatalf("failed to generate CA: %v", err)
	}
	uc, err := testutil.GenerateTestUserCert(ca, "test1234")
	if err != nil {
		t.Fatalf("failed to generate user cert: %v", err)
	}

	cp := NewCertProcessor(logr.Logger{})
	ctx := context.Background()

	tests := map[string]struct {
		build func() ([]byte, string, error)
	}{
		"CreateTruststore": {
			build: func() ([]byte, string, error) {
				return cp.CreateTruststore(ctx, ca.CACertPEM, "")
			},
		},
		"CreateKeystore": {
			build: func() ([]byte, string, error) {
				return cp.CreateKeystore(ctx, ca.CACertPEM, uc.UserCertPEM, uc.UserKeyPEM, "", "")
			},
		},
		"GenerateTLSforHTTP": {
			build: func() ([]byte, string, error) {
				return cp.GenerateTLSforHTTP(ctx, ca.CACertPEM, ca.CAKeyPEM, "", "confluent-schema-registry", "kafka")
			},
		},
		"ConvertPEMToJKS": {
			build: func() ([]byte, string, error) {
				return cp.ConvertPEMToJKS(ctx, uc.UserCertPEM, uc.UserKeyPEM, "", "")
			},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			jks, password, err := tt.build()
			if err != nil {
				t.Fatalf("failed to build the keystore: %v", err)
			}
			if len(password) != 24 {
				t.Errorf("expected an auto-generated 24-character password, got %d characters", len(password))
			}
			for _, r := range password {
				if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
					t.Errorf("auto-generated password contains an unexpected character %q", r)
				}
			}

			store := keystore.New()
			if err := store.Load(bytes.NewReader(jks), []byte(password)); err != nil {
				t.Errorf("expected the returned password to open the keystore, got %v", err)
			}
		})
	}
}

// TestPasswordNeverLeaksIntoErrorsOrLogs verifies that the keystore password
// is sealed into the JKS bytes only: no returned error message and no log
// record ever contains it.
func TestPasswordNeverLeaksIntoErrorsOrLogs(t *testing.T) {
	const pw = "s3cret-PW-123"

	ca, err := testutil.GenerateTestCA()
	if err != nil {
		t.Fatalf("failed to generate CA: %v", err)
	}
	uc, err := testutil.GenerateTestUserCert(ca, pw)
	if err != nil {
		t.Fatalf("failed to generate user cert: %v", err)
	}
	other, err := testutil.GenerateTestUserCert(ca, pw)
	if err != nil {
		t.Fatalf("failed to generate a second user cert: %v", err)
	}

	sink := &captureSink{}
	cp := NewCertProcessor(logr.New(sink))
	ctx := context.Background()

	failures := map[string]func() error{
		"CreateTruststore with an empty ca.crt": func() error {
			_, _, err := cp.CreateTruststore(ctx, "", pw)
			return err
		},
		"CreateKeystore with a key/certificate mismatch": func() error {
			_, _, err := cp.CreateKeystore(ctx, ca.CACertPEM, uc.UserCertPEM, other.UserKeyPEM, "", pw)
			return err
		},
		"GenerateTLSforHTTP with an empty ca.crt": func() error {
			_, _, err := cp.GenerateTLSforHTTP(ctx, "", ca.CAKeyPEM, pw, "confluent-schema-registry", "kafka")
			return err
		},
		"ConvertPEMToJKS with an unparseable ca.crt": func() error {
			_, _, err := cp.ConvertPEMToJKS(ctx, uc.UserCertPEM, uc.UserKeyPEM, "not a certificate", pw)
			return err
		},
		"KeystoreCertExpiry with a wrong password": func() error {
			jks, _, err := cp.CreateTruststore(ctx, ca.CACertPEM, pw)
			if err != nil {
				return err
			}
			_, err = cp.KeystoreCertExpiry(ctx, jks, pw+"x")
			return err
		},
	}

	for name, fail := range failures {
		t.Run(name, func(t *testing.T) {
			before := len(sink.messages)
			err := fail()
			if err == nil {
				t.Fatal("expected an error")
			}
			if strings.Contains(err.Error(), pw) {
				t.Errorf("the password leaked into the error message: %q", err.Error())
			}
			for _, msg := range sink.messages[before:] {
				if strings.Contains(msg, pw) {
					t.Errorf("the password leaked into the log output: %q", msg)
				}
			}
		})
	}
}
